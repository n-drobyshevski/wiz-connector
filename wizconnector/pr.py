"""Open / update / close the automated bump pull request.

  python -m wizconnector pr --out-dir R --issue-number N [--base main]

Commits ONLY the pom.xml files changed by `wizconnector apply` to the fixed branch
wiz-connector/maven-bumps and creates or updates one PR (draft while the build fails).
The branch is rewritten only while it contains nothing but bot commits: as soon as a person or
Copilot pushes to it, the bot leaves it alone. When nothing can be applied any more, an open
bot PR is closed.
"""

from __future__ import annotations

import json
import os
import re
import subprocess
from dataclasses import dataclass
from pathlib import Path

from .commands import md
from .render import PR_BRANCH

PR_MARKER = "<!-- wiz-connector:maven-bumps-pr -->"
BOT_NAME = "github-actions[bot]"
BOT_EMAIL = "41898282+github-actions[bot]@users.noreply.github.com"
BOT_LOGINS = {"app/github-actions", "github-actions", "github-actions[bot]"}
_POM = re.compile(r"(^|/)pom\.xml$")


@dataclass
class Outcome:
    action: str              # created | updated | unchanged | closed | skipped | none
    number: int | None = None
    detail: str = ""


def _git(*args: str, cwd: Path, check: bool = True) -> str:
    res = subprocess.run(["git", *args], cwd=cwd, capture_output=True, text=True)
    if check and res.returncode:
        raise RuntimeError(f"git {' '.join(args)} failed: {res.stderr.strip()[:500]}")
    return res.stdout.strip()


def _gh(*args: str, check: bool = True) -> str:
    res = subprocess.run(["gh", *args], capture_output=True, text=True)
    if check and res.returncode:
        raise RuntimeError(f"gh {' '.join(args[:3])} failed: {res.stderr.strip()[:500]}")
    return res.stdout.strip()


def changed_poms(repo: Path) -> list[str]:
    """Tracked pom.xml files modified in the working tree (nothing else is ever committed)."""
    out = _git("diff", "--name-only", "HEAD", "--", cwd=repo)
    return sorted(f for f in out.splitlines() if f.strip() and _POM.search(f.strip()))


def pr_body(report: dict, result: dict, issue: int | None) -> str:
    rows = report.get("upgrades", [])
    applied = set(result.get("applied_rows", []))
    pending = {int(k): v for k, v in result.get("pending", {}).items()}
    v = result.get("verify", {})
    ok = v.get("ok")
    ref = f"#{issue}" if issue else "the wiz-sca tracking issue"
    lines = [PR_MARKER,
             f"Automated security bumps for direct Maven dependencies, generated by wiz-connector from {ref}.",
             "", "| # | Dependency | Bump | CVEs |", "|--:|---|---|---|"]
    for i, r in enumerate(rows, 1):
        if i in applied:
            cves = ", ".join(r.get("cves", [])[:5]) + (f" +{len(r['cves']) - 5}" if len(r.get("cves", [])) > 5 else "")
            lines.append(f"| {i} | `{md(r['ga'])}` | `{md(r['current'])}` → `{md(r['target'])}` | {md(cves)} |")
    lines.append("")
    if ok:
        lines.append(f"**Build:** `{md(v.get('cmd'))}` passed.")
    elif ok is False:
        lines += [f"**Build:** `{md(v.get('cmd'))}` **failed**: this PR stays a draft until the breakage is fixed "
                  "(Copilot: fix only what the bumps broke, on this branch).", "",
                  "<details><summary>Build log (tail)</summary>", "", "```text",
                  v.get("log_tail", "").replace("```", "'''"), "```", "</details>"]
    if pending:
        lines += ["", f"**Still to do** (see {ref}; Copilot: run `/wiz-maven-bumps` on it and push to this branch):"]
        for i, why in sorted(pending.items()):
            if i <= len(rows):
                lines.append(f"- row {i} `{md(rows[i - 1]['ga'])}` → `{md(rows[i - 1]['target'])}`: {md(why)}")
    lines += ["", (f"Fixes #{issue}" if issue and ok and not pending else (f"Refs #{issue}" if issue else ""))]
    return "\n".join(lines).rstrip() + "\n"


def _remote_branch(repo: Path) -> str | None:
    _git("fetch", "--quiet", "origin", f"+refs/heads/{PR_BRANCH}:refs/remotes/origin/{PR_BRANCH}", cwd=repo, check=False)
    sha = _git("rev-parse", "--verify", "--quiet", f"refs/remotes/origin/{PR_BRANCH}", cwd=repo, check=False)
    return sha or None


def _foreign_commits(repo: Path, base: str, remote_sha: str) -> list[str]:
    emails = _git("log", "--format=%ae", f"{base}..{remote_sha}", cwd=repo, check=False).splitlines()
    return [e for e in emails if e and e != BOT_EMAIL]


def run(repo_slug: str, repo: Path, out_dir: Path, issue: int | None, base_branch: str,
        labels: list[str], dry_run: bool = False) -> Outcome:
    report = json.loads((out_dir / "report.json").read_text(encoding="utf-8"))
    rpath = out_dir / "apply-result.json"
    if not rpath.is_file():
        return Outcome("skipped", None, "no apply-result.json (auto-apply did not run); PR left as is")
    result = json.loads(rpath.read_text(encoding="utf-8"))
    if result.get("error") or result.get("fingerprint") != report.get("fingerprint"):
        return Outcome("skipped", None, "auto-apply failed or is stale; PR left as is")
    existing = [p for p in json.loads(_gh("pr", "list", "--repo", repo_slug, "--head", PR_BRANCH, "--state", "open",
                                          "--json", "number,isDraft,author,body")) or []
                if (p.get("author") or {}).get("login", "").lower() in BOT_LOGINS
                and (p.get("body") or "").startswith(PR_MARKER)]
    current = existing[0] if existing else None
    files = changed_poms(repo)

    if not result.get("applied_rows") or not files:
        if current and not dry_run:
            _gh("pr", "close", str(current["number"]), "--repo", repo_slug, "--delete-branch",
                "--comment", "No automatic bumps are left (fixed, or now handled by hand). Closing.")
            return Outcome("closed", current["number"])
        return Outcome("none")

    base = _git("rev-parse", "HEAD", cwd=repo)
    remote_sha = _remote_branch(repo)
    if remote_sha and _foreign_commits(repo, base, remote_sha):
        return Outcome("skipped", current["number"] if current else None,
                       f"{PR_BRANCH} has commits by someone else; not rewriting it")

    _git("checkout", "-q", "-B", PR_BRANCH, cwd=repo)
    _git("add", "--", *files, cwd=repo)
    rows = report.get("upgrades", [])
    names = ", ".join(rows[i - 1]["ga"].split(":")[1] for i in result["applied_rows"] if i <= len(rows))
    msg = f"fix(deps): security bumps from Wiz ({names})" + (f"\n\nRefs #{issue}" if issue else "")
    _git("-c", f"user.name={BOT_NAME}", "-c", f"user.email={BOT_EMAIL}", "commit", "-q", "-m", msg, cwd=repo)

    same_tree = bool(remote_sha) and (_git("rev-parse", "HEAD^{tree}", cwd=repo)
                                      == _git("rev-parse", f"{remote_sha}^{{tree}}", cwd=repo, check=False))
    body = pr_body(report, result, issue)
    draft = result.get("verify", {}).get("ok") is not True
    if dry_run:
        return Outcome("dry-run", current["number"] if current else None, body)
    if not same_tree:
        lease = f"--force-with-lease={PR_BRANCH}:{remote_sha or ''}"
        _git("push", "--quiet", lease, "origin", f"HEAD:refs/heads/{PR_BRANCH}", cwd=repo)
    body_file = out_dir / "pr-body.md"
    body_file.write_text(body, encoding="utf-8")
    title = f"fix(deps): security bumps from Wiz ({len(result['applied_rows'])} direct dependencies)"
    if current:
        n = current["number"]
        _gh("pr", "edit", str(n), "--repo", repo_slug, "--title", title, "--body-file", str(body_file))
        if current.get("isDraft") and not draft:
            _gh("pr", "ready", str(n), "--repo", repo_slug, check=False)
        elif not current.get("isDraft") and draft:
            _gh("pr", "ready", str(n), "--repo", repo_slug, "--undo", check=False)
        return Outcome("unchanged" if same_tree else "updated", n)
    args = ["pr", "create", "--repo", repo_slug, "--head", PR_BRANCH, "--base", base_branch,
            "--title", title, "--body-file", str(body_file)]
    if draft:
        args.append("--draft")
    url = _gh(*args)
    n = int(url.rstrip("/").rsplit("/", 1)[-1]) if url else None
    for lb in labels:
        _gh("pr", "edit", str(n), "--repo", repo_slug, "--add-label", lb, check=False)
    return Outcome("created", n)


def main(repo_slug: str, repo_root: str, out_dir: str, issue: str | None, base_branch: str,
         labels: list[str], dry_run: bool) -> Outcome:
    num = int(issue) if issue and str(issue).isdigit() else None
    if num is None:
        f = Path(out_dir) / "issue.json"
        if f.is_file():
            num = json.loads(f.read_text(encoding="utf-8")).get("number")
    return run(repo_slug, Path(repo_root).resolve(), Path(out_dir), num, base_branch, labels,
               dry_run or os.environ.get("GH_AW_SAFE_OUTPUTS_STAGED", "").lower() == "true")
