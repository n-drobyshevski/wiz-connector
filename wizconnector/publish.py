"""Create / update / replace / close the single tracking issue.

Idempotent and hijack-resistant: an issue counts as ours only if it was opened by a trusted
author (the workflow's bot identity by default) AND its FIRST line is the exact marker. A body
that differs from what we would render (someone edited it) is rewritten.
"""

from __future__ import annotations

import json
import os
import re
import subprocess
from dataclasses import dataclass

from .render import MARKER, _md

_HEAD = re.compile(r"^<!-- " + re.escape(MARKER) + r" fingerprint=([0-9a-f]{16}) -->$")
_JSON = re.compile(r"```json\n(.*?)\n```", re.S)
# Issues created with GITHUB_TOKEN are authored by the GitHub Actions app.
DEFAULT_TRUSTED_AUTHORS = ("app/github-actions", "github-actions", "github-actions[bot]")


@dataclass
class Plan:
    action: str                 # create | update | replace | noop | close | none
    number: int | None = None
    duplicates: tuple = ()
    comment: str | None = None


def head_fingerprint(body: str) -> str | None:
    first = (body or "").split("\n", 1)[0].strip()
    m = _HEAD.match(first)
    return m.group(1) if m else None


def stable(body: str) -> str:
    """Body without the per-run volatile parts (timestamp/run link), for tamper detection."""
    out = []
    for line in (body or "").replace("\r\n", "\n").split("\n"):
        if line.startswith("> Generated by wiz-connector"):
            continue
        if line.lstrip().startswith(('"generated_at":', '"run_url":')):
            continue
        out.append(line.rstrip())
    return "\n".join(out).strip()


def _author(issue: dict) -> str:
    a = issue.get("author") or {}
    return (a.get("login") if isinstance(a, dict) else str(a)) or ""


def ours(existing: list[dict], trusted_authors=DEFAULT_TRUSTED_AUTHORS) -> list[dict]:
    trusted = {t.lower() for t in trusted_authors}
    return sorted((i for i in existing
                   if _author(i).lower() in trusted and head_fingerprint(i.get("body") or "")),
                  key=lambda i: i["number"])


def previous_upgrades(body: str) -> dict[str, str]:
    m = _JSON.search(body or "")
    if not m:
        return {}
    try:
        data = json.loads(m.group(1))
    except json.JSONDecodeError:
        return {}
    return {str(u["ga"]): str(u.get("target")) for u in data.get("upgrades", []) if isinstance(u, dict) and "ga" in u}


def delta_comment(old: dict[str, str], new: dict[str, str]) -> str | None:
    added = sorted(set(new) - set(old))
    removed = sorted(set(old) - set(new))
    retarget = sorted(g for g in set(old) & set(new) if old[g] != new[g])
    if not (added or removed or retarget):
        return "Wiz findings changed (CVE list updated); dependency targets are unchanged."
    parts = []
    if added:
        parts.append("**New:** " + ", ".join(f"`{_md(g)}` → `{_md(new[g])}`" for g in added))
    if retarget:
        parts.append("**New target:** " + ", ".join(f"`{_md(g)}` `{_md(old[g])}` → `{_md(new[g])}`" for g in retarget))
    if removed:
        parts.append("**Resolved / no longer listed:** " + ", ".join(f"`{_md(g)}`" for g in removed))
    return "Issue body refreshed from the latest Wiz scan.\n\n" + "\n".join(f"- {p}" for p in parts)


def plan(existing: list[dict], new_fingerprint: str, new_upgrades: dict[str, str], close_when_clean: bool,
         on_change: str = "update", new_body: str | None = None,
         trusted_authors=DEFAULT_TRUSTED_AUTHORS) -> Plan:
    """on_change="update" edits the open issue in place (best when people run Copilot in VS Code on
    the current issue). on_change="replace" closes it and opens a fresh one when the findings change,
    for issues assigned to the Copilot cloud agent, which ignores edits made after assignment."""
    mine = ours(existing, trusted_authors)
    if not mine:
        return Plan("create") if new_upgrades else Plan("none")
    keep, dups = mine[0], tuple(i["number"] for i in mine[1:])
    if not new_upgrades:
        if close_when_clean:
            return Plan("close", keep["number"], dups,
                        "Wiz reports no open vulnerabilities in direct Maven dependencies any more. Closing.")
        return Plan("noop", keep["number"], dups)
    old_body = keep.get("body") or ""
    if head_fingerprint(old_body) == new_fingerprint:
        if new_body is None or stable(old_body) == stable(new_body):
            return Plan("noop", keep["number"], dups)
        return Plan("update", keep["number"], dups, None)      # same findings, body was edited: restore it
    comment = delta_comment(previous_upgrades(old_body), new_upgrades)
    return Plan("replace" if on_change == "replace" else "update", keep["number"], dups, comment)


def _assign(repo: str, number: int, assignees: list[str]) -> None:
    """Assigning Copilot ("@copilot") needs a user token (fine-grained PAT) in COPILOT_ASSIGN_TOKEN;
    GITHUB_TOKEN and GitHub App tokens are rejected for Copilot assignment. Failures are non-fatal."""
    env = dict(os.environ)
    if os.environ.get("COPILOT_ASSIGN_TOKEN"):
        env["GH_TOKEN"] = os.environ["COPILOT_ASSIGN_TOKEN"]
    args = ["gh", "issue", "edit", str(number), "--repo", repo]
    for a in assignees:
        args += ["--add-assignee", a]
    res = subprocess.run(args, capture_output=True, text=True, env=env)
    if res.returncode:
        print(f"::warning::could not assign {assignees} to #{number}: {res.stderr.strip()[:300]}")


def _gh(*args: str, check: bool = True) -> str:
    res = subprocess.run(["gh", *args], capture_output=True, text=True, check=check)
    return res.stdout


def execute(repo: str, label: str, title: str, body_file: str, fingerprint: str,
            upgrades: dict[str, str], close_when_clean: bool = True, assignees: list[str] | None = None,
            extra_labels: list[str] | None = None, dry_run: bool = False, on_change: str = "update",
            trusted_authors=DEFAULT_TRUSTED_AUTHORS) -> Plan:
    existing = json.loads(_gh("issue", "list", "--repo", repo, "--label", label, "--state", "open",
                              "--limit", "200", "--json", "number,title,body,author"))
    with open(body_file, encoding="utf-8") as fh:
        new_body = fh.read()
    p = plan(existing, fingerprint, upgrades, close_when_clean, on_change, new_body, trusted_authors)
    if dry_run:
        return p
    labels = [label, *(extra_labels or [])]
    if p.action in ("create", "replace"):
        for lb in labels:   # create if missing; never overwrite an existing label's colour/description
            _gh("label", "create", lb, "--repo", repo, "--color", "B60205",
                "--description", "Managed by wiz-connector", check=False)
    if p.action in ("create", "replace"):
        old = p.number
        args = ["issue", "create", "--repo", repo, "--title", title, "--body-file", body_file]
        for lb in labels:
            args += ["--label", lb]
        out = _gh(*args).strip()
        p.number = int(out.rstrip("/").rsplit("/", 1)[-1]) if out else None
        if assignees and p.number:
            _assign(repo, p.number, assignees)
        if p.action == "replace" and old:
            _gh("issue", "close", str(old), "--repo", repo, "--reason", "not planned",
                "--comment", f"Superseded by #{p.number}: {p.comment or 'findings changed'}")
    elif p.action == "update":
        _gh("issue", "edit", str(p.number), "--repo", repo, "--title", title, "--body-file", body_file)
        if p.comment:
            _gh("issue", "comment", str(p.number), "--repo", repo, "--body", p.comment)
    elif p.action == "close":
        _gh("issue", "close", str(p.number), "--repo", repo, "--reason", "completed", "--comment", p.comment or "")
    for d in p.duplicates:
        _gh("issue", "close", str(d), "--repo", repo, "--reason", "not planned",
            "--comment", f"Duplicate of #{p.number} (managed by wiz-connector).")
    return p
